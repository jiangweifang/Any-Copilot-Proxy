def tr(language: str, key: str, **values) -> str:
    return TEXT[language][key].format(**values)


def localize_message(language: str, message: str) -> str:
    if language != "zh" or not message:
        return message
    if message in ERRORS_ZH:
        return ERRORS_ZH[message]
    for prefix, key in (("Listener update failed; previous settings and service were restored. ", "listener_rollback"),
                        ("Listener update failed and rollback was incomplete: ", "listener_rollback_failed")):
        if message.startswith(prefix):
            return tr(language, key, message=localize_message(language, message[len(prefix):]))
    if match := re.fullmatch(r"Connection and authorization OK; (\d+) chat models\.", message):
        return tr(language, "proxy_ok", count=match[1])
    if message == TEXT["en"]["github_ok"]:
        return tr(language, "github_ok")
    prefix = "Proxy applied; model refresh failed: "
    if message.startswith(prefix):
        return tr(language, "proxy_refresh_failed", message=localize_message(language, message[len(prefix):]))
    if match := re.fullmatch(r"(?:Upstream|Copilot) returned HTTP (\d+)\.", message):
        return f"上游服务返回 HTTP {match[1]}。"
    return message
